#!/usr/bin/env python3
"""Build a customer-specific plugin from selected finance skills. Stdlib only.

Reads skills from the plugin-local, vendored ``templates/`` tree (never sibling
plugins), so the containing plugin is self-contained and zip-shippable. Source
hydration hints are consumed from pre-parsed ``hydration_hints.json`` sidecars
vendored next to each template; generated hints are emitted as
``hydration_hints.yaml`` via the dependency-free ``_minyaml`` writer.

Output safety: every generated plugin carries a ``.finance-hydrator`` marker.
An existing, non-empty output directory without that marker is never deleted
unless ``--force`` is passed, and the filesystem root, the home directory and
the hydrator plugin itself (or any of its ancestors) are always refused.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path
from typing import Any

import _minyaml

# scripts -> engine -> <skill> ; templates + catalog live under <skill>
SKILL_ROOT = Path(__file__).resolve().parents[2]
HYDRATOR_PLUGIN_DIR = SKILL_ROOT.parents[1]
DEFAULT_TEMPLATES_ROOT = SKILL_ROOT / "templates"
EVAL_ALLOWLIST = {"golden_cases.md", "eval_plan.md", "README.md"}
MARKER_NAME = ".finance-hydrator"
SKILL_NAME_RE = re.compile(r"^[a-z0-9_]+$")
PLACEHOLDER_RE = re.compile(r"<[^<>]*>|\bYOUR_")


class RefuseOutput(Exception):
    """The requested output directory is unsafe to write or clear."""


def has_placeholder(value: object) -> bool:
    return isinstance(value, str) and bool(PLACEHOLDER_RE.search(value))


def load_json(path: Path) -> dict[str, Any]:
    try:
        with path.open("r", encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"build_customer_plugin.py: error: cannot read {path}: {exc}")
    if not isinstance(data, dict):
        raise SystemExit(f"build_customer_plugin.py: error: {path} must contain a JSON object")
    return data


def load_catalogs(paths: list[Path]) -> dict[tuple[str, str], dict[str, Any]]:
    lookup: dict[tuple[str, str], dict[str, Any]] = {}
    for path in paths:
        catalog = load_json(path)
        domain = catalog["domain"]
        source_plugin = catalog["source_plugin"]
        for skill in catalog.get("skills", []):
            name = str(skill.get("name", ""))
            if not SKILL_NAME_RE.match(name):
                raise SystemExit(
                    f"{path}: invalid skill name {name!r} (must match {SKILL_NAME_RE.pattern})"
                )
            entry = dict(skill)
            entry["domain"] = domain
            entry["source_plugin"] = source_plugin
            lookup[(domain, name)] = entry
    return lookup


def contained(path: Path, root: Path, what: str) -> Path:
    """Resolve ``path`` and fail unless it stays inside ``root``."""
    resolved = path.resolve()
    if resolved != root and root not in resolved.parents:
        raise SystemExit(f"{what} escapes {root}: {resolved}")
    return resolved


def check_output_dir(output: Path, force: bool) -> None:
    """Refuse dangerous outputs; clear a previous generated plugin if safe."""
    forbidden = {Path("/").resolve(), Path.home().resolve()}
    if output in forbidden:
        raise RefuseOutput(f"refusing to write to {output}")
    if output == HYDRATOR_PLUGIN_DIR or output in HYDRATOR_PLUGIN_DIR.parents:
        raise RefuseOutput(
            f"refusing to write to {output}: it contains the finance-hydrator plugin"
        )
    if not output.exists():
        return
    if not output.is_dir():
        raise RefuseOutput(f"output {output} exists and is not a directory")
    if not any(output.iterdir()):
        return
    if not (output / MARKER_NAME).exists() and not force:
        raise RefuseOutput(
            f"output {output} is not empty and was not generated by finance-hydrator "
            f"(no {MARKER_NAME} marker). Choose another --output or pass --force to "
            "replace its contents."
        )
    shutil.rmtree(output)


def write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def write_readme(output_dir: Path, selected: list[dict[str, Any]]) -> None:
    lines = [
        "# Customer Finance Plugin",
        "",
        "Generated by Finance Hydrator.",
        "",
        "## Included skills",
        "",
        "| Domain | Skill | Status | Readiness |",
        "|---|---|---|---:|",
    ]
    for item in selected:
        lines.append(
            f"| {item['domain']} | `{item['skill']}` | {item.get('status', 'UNKNOWN')} | {item.get('readiness', 0)}% |"
        )
    lines.extend(
        [
            "",
            "Settings that still need a value are listed under `unresolved:` in each",
            "skill's `hydration_hints.yaml`.",
            "",
            "## Activate",
            "",
            "```bash",
            "cortex plugin add <path-to-plugin>",
            "/plugin reload",
            "```",
            "",
        ]
    )
    output_dir.joinpath("README.md").write_text("\n".join(lines), encoding="utf-8")


def should_build_skill(item: dict[str, Any], include_partial: bool) -> bool:
    """Return whether an assessment row should be copied into the generated plugin.

    Older readiness-only assessments used `status` (READY/PARTIAL/BLOCKED). The improved
    recommendation flow adds `recommendation` and `final_status` so low-fit READY skills can be
    excluded. Prefer `recommendation` when present; fall back to readiness status for backwards
    compatibility with existing fixtures and scripts.
    """
    recommendation = item.get("recommendation")
    if recommendation == "include":
        return True
    if recommendation == "ask":
        return include_partial
    if recommendation == "exclude":
        return False
    return item.get("status") == "READY" or (include_partial and item.get("status") == "PARTIAL")


def copy_eval_plan_files(src: Path, dst: Path) -> bool:
    """Copy only eval plans/golden cases into generated customer plugins.

    Prior eval results were produced against source/internal data and are not
    relevant after hydration. Only ship files that help the customer smoke test
    the hydrated skill in their own account.
    """
    copied = False
    if dst.exists():
        shutil.rmtree(dst)
    for name in sorted(EVAL_ALLOWLIST):
        source = src / name
        if source.exists() and source.is_file():
            dst.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, dst / name)
            copied = True
    return copied


def required_flags(entry: dict[str, Any]) -> dict[str, bool]:
    """Map each catalog data_need key to its required flag."""
    return {n["key"]: bool(n.get("required")) for n in entry.get("data_needs", [])}


def is_required(value: Any) -> bool:
    return value in {"yes", True}


def load_source_hints(dest: Path) -> dict[str, Any]:
    """Load a vendored source hint sidecar (JSON) if the template shipped one.

    Each source ``hydration_hints.yaml`` is pre-parsed into a
    ``hydration_hints.json`` sidecar so runtime never needs a YAML parser.
    """
    sidecar = dest / "hydration_hints.json"
    if sidecar.exists():
        return load_json(sidecar)
    return {}


def split_placeholders(settings: Any) -> tuple[Any, Any]:
    """Split a settings tree into (resolved, placeholder-only) parts."""
    if isinstance(settings, dict):
        kept: dict[str, Any] = {}
        moved: dict[str, Any] = {}
        for key, value in settings.items():
            keep, move = split_placeholders(value)
            if keep is not None:
                kept[key] = keep
            if move is not None:
                moved[key] = move
        return kept, (moved or None)
    if has_placeholder(settings):
        return None, settings
    return settings, None


def write_hydration_hints(dest: Path, item: dict[str, Any], entry: dict[str, Any]) -> None:
    """Merge resolved bindings into hydration_hints.yaml.

    When the copied skill shipped a source hint sidecar, preserve its structure
    (format_version, plugin, skill, synonyms, grain, read_from, extra_settings,
    ...) and only fill the resolved fqn/columns. When no sidecar exists,
    synthesize a minimal file. The ``required`` flag is taken from the catalog,
    not hardcoded, so optional needs are not mislabeled as required.

    Nothing unresolved is written inline: unbound optional needs, still-placeholder
    columns and placeholder extra_settings move to a top-level ``unresolved:``
    block so the bound configuration stays clean and validators can tell
    "needs a value" apart from "broken".
    """
    bindings = item.get("bindings") or {}
    # The sidecar is a build-time input only; never ship it in the customer plugin.
    sidecar = dest / "hydration_hints.json"
    data = load_source_hints(dest)
    if sidecar.exists():
        sidecar.unlink()
    if not bindings:
        return

    flags = required_flags(entry)
    hints_path = dest / "hydration_hints.yaml"
    source_needs: dict[str, Any] = data.get("data_needs") or {}
    data_needs: dict[str, Any] = {}
    unresolved: dict[str, Any] = {}

    for key, binding in bindings.items():
        required_value = "yes" if flags.get(key) else "no"
        fqn = binding.get("fqn", "")
        columns = binding.get("columns", {}) or {}
        need = source_needs.get(key)
        if not isinstance(need, dict):
            need = {"sources": [{"fqn": fqn, "columns": columns}]}
        # Preserve the existing need; update only the binding-critical fields.
        need["required"] = required_value
        sources = need.get("sources")
        if not isinstance(sources, list) or not sources:
            sources = [{}]
        first = sources[0] if isinstance(sources[0], dict) else {}
        first["fqn"] = fqn
        # Propagate object_type (e.g. "procedure") so the skill knows access mode.
        if binding.get("object_type"):
            first["object_type"] = binding["object_type"]
        merged_columns = dict(first.get("columns") or {})
        merged_columns.update(columns)
        # Required columns are guaranteed resolved by the scorer, so any
        # remaining placeholder is an unresolved optional column.
        first["columns"] = {c: v for c, v in merged_columns.items() if not has_placeholder(v)}
        open_columns = sorted(c for c, v in merged_columns.items() if has_placeholder(v))
        if open_columns:
            unresolved.setdefault("columns", {})[key] = open_columns
        sources[0] = first
        need["sources"] = sources
        if "extra_settings" in need:
            kept, moved = split_placeholders(need["extra_settings"])
            need["extra_settings"] = kept or {}
            if moved:
                unresolved.setdefault("extra_settings", {})[key] = moved
        data_needs[key] = need

    # Needs with no binding: optional ones go to `unresolved`; a required one is
    # kept (with its placeholders) so validate_bindings.py fails loudly.
    catalog_needs = {n["key"]: n for n in entry.get("data_needs", [])}
    unbound_keys = list(dict.fromkeys([*source_needs, *catalog_needs]))
    for key in unbound_keys:
        if key in bindings:
            continue
        need = source_needs.get(key) if isinstance(source_needs.get(key), dict) else {}
        required = flags[key] if key in flags else is_required(need.get("required"))
        if required:
            need["required"] = "yes"
            data_needs[key] = need
            continue
        hint: dict[str, Any] = {"required": "no", "reason": "no official source bound"}
        if need.get("synonyms"):
            hint["synonyms"] = need["synonyms"]
        description = catalog_needs.get(key, {}).get("concepts")
        if description:
            hint["concepts"] = description
        unresolved.setdefault("data_needs", {})[key] = hint

    data["data_needs"] = data_needs
    if "extra_settings" in data:
        kept, moved = split_placeholders(data["extra_settings"])
        data["extra_settings"] = kept or {}
        if moved:
            unresolved.setdefault("extra_settings", {})["_top_level"] = moved
    data.pop("unresolved", None)
    if unresolved:
        data["unresolved"] = unresolved

    dest.mkdir(parents=True, exist_ok=True)
    hints_path.write_text(_minyaml.dump(data), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--assessment", type=Path, required=True)
    parser.add_argument("--catalog", action="append", type=Path, required=True)
    parser.add_argument("--templates-root", type=Path, default=DEFAULT_TEMPLATES_ROOT)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--include-partial", action="store_true")
    parser.add_argument(
        "--skills",
        help="Comma-separated skills the user selected. When set, builds exactly these "
        "(BLOCKED skills are still refused) instead of the include/ask defaults.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Replace a non-empty --output that was not generated by finance-hydrator.",
    )
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    templates_root = args.templates_root.resolve()
    output = args.output.resolve()
    assessment = load_json(args.assessment)
    catalog = load_catalogs([path.resolve() for path in args.catalog])
    rows = assessment.get("skills", [])
    if args.skills:
        wanted = {s.strip() for s in args.skills.split(",") if s.strip()}
        known = {item.get("skill") for item in rows}
        unknown = sorted(wanted - known)
        blocked = sorted(
            item["skill"]
            for item in rows
            if item.get("skill") in wanted
            and "BLOCKED" in {item.get("final_status"), item.get("data_status"), item.get("status")}
        )
        if unknown or blocked:
            print(
                "build_customer_plugin.py: error: "
                + (f"unknown skills {unknown} " if unknown else "")
                + (f"blocked skills {blocked} cannot be built" if blocked else ""),
                file=sys.stderr,
            )
            return 1
        selected = [item for item in rows if item.get("skill") in wanted]
    else:
        selected = [item for item in rows if should_build_skill(item, args.include_partial)]
    if not selected:
        print(
            "build_customer_plugin.py: error: no skills selected for the build. "
            "Include at least one RECOMMENDED skill, or pass --include-partial for "
            "approved ASK/OPTIONAL skills.",
            file=sys.stderr,
        )
        return 1

    plan: list[dict[str, str]] = []
    for item in selected:
        entry = catalog.get((item["domain"], item["skill"]))
        if not entry:
            raise SystemExit(f"No catalog entry for {item['domain']}.{item['skill']}")
        plugin_root = templates_root / entry["source_plugin"]
        source = contained(plugin_root / entry["source_dir"], templates_root, "template source_dir")
        if not source.exists():
            raise SystemExit(
                f"Vendored template missing for {item['domain']}.{item['skill']}: {source}."
            )
        dest = contained(output / "skills" / item["skill"], output, "skill destination")
        eval_source = None
        eval_dir = entry.get("eval_dir")
        if eval_dir:
            candidate = contained(plugin_root / eval_dir, templates_root, "template eval_dir")
            if candidate.exists():
                eval_source = candidate
        eval_dest = (
            contained(output / "evals" / item["skill"], output, "eval destination")
            if eval_source
            else None
        )
        plan.append(
            {
                "source": str(source),
                "dest": str(dest),
                "eval_source": str(eval_source) if eval_source else "",
                "eval_dest": str(eval_dest) if eval_dest else "",
            }
        )

    if args.dry_run:
        print(json.dumps({"selected": selected, "copy_plan": plan}, indent=2))
        return 0

    try:
        check_output_dir(output, args.force)
    except RefuseOutput as exc:
        print(f"build_customer_plugin.py: error: {exc}", file=sys.stderr)
        return 2
    output.mkdir(parents=True, exist_ok=True)
    (output / MARKER_NAME).write_text(
        "Generated by finance-hydrator. Safe for build_customer_plugin.py to replace.\n",
        encoding="utf-8",
    )

    write_json(
        output / ".cortex-plugin" / "plugin.json",
        {
            "name": "customer-finance",
            "description": "Customer-specific Finance plugin generated by Finance Hydrator.",
            "version": "0.1.0",
        },
    )

    selected_by_dest = {str(output / "skills" / item["skill"]): item for item in selected}
    entry_by_dest = {
        str(output / "skills" / item["skill"]): catalog[(item["domain"], item["skill"])]
        for item in selected
    }
    for copy in plan:
        shutil.copytree(copy["source"], copy["dest"])
        if copy.get("eval_source") and copy.get("eval_dest"):
            copy_eval_plan_files(Path(copy["eval_source"]), Path(copy["eval_dest"]))
        item = selected_by_dest.get(copy["dest"])
        entry = entry_by_dest.get(copy["dest"])
        if item and entry:
            write_hydration_hints(Path(copy["dest"]), item, entry)
    write_readme(output, selected)
    print(json.dumps({"status": "OK", "output": str(output), "skills": selected}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
