def _make_merged_assessment() -> Assessment:
    """Minimal Assessment with file_info + files + one finding."""
    return Assessment(
        files=[
            FileCompatibilityRow(
                path="src/main.py", name="main.py",
                technology="Python", lines=120, spark_usages=3, issues=1, status="Low",
            ),
            FileCompatibilityRow(
                path="src/utils.py", name="utils.py",
                technology="Python", lines=40, spark_usages=0, issues=0, status="High",
            ),
        ],
        file_info=[
            FileInfoRow(
                path="src/main.py", name="main.py",
                source_system=["S3"], target_type=["Snowflake Table"],
                eai_required="No", ar_required="Yes", ar_packages=["pygeohash"],
                lines=120,
            ),
            FileInfoRow(
                path="src/utils.py", name="utils.py",
                source_system=["N/A"], target_type=["N/A"],
                eai_required="No", ar_required="No",
                lines=40,
            ),
        ],
        detailed_findings=[
            DetailedFinding(
                file="src/main.py", name="main.py", lines="45-45",
                language="python", severity="High", final_risk=0.9,
                confidence="HIGH", category="RDD / SparkContext",
                root_cause="RDD operations are unsupported",
                explanation="Spark Connect does not support RDDs.",
                fix="Replace with DataFrame API.",
            ),
        ],
    )


