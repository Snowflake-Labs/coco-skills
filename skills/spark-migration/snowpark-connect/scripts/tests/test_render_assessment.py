"""Tier-B integration tests for ``render_assessment.build_assessment``.

Focus areas (kept independent from ``scripts/assessment/tests/test_assess.py``,
which already covers the legacy single-source path in depth):

* Backward-compat path: no new flags → behaviour is the legacy one.
* New flag path: ``--migration-state-json`` (no explicit source dir) →
  renderer materializes ``phase-0-source`` itself, populates the
  recipe-resolved panel from ``migration_state.json[recipe_edits]``.
* Post-merge panel assignment: the panel is wired in
  ``Assessment.recipe_resolved`` AFTER the IR merge — no per-merge math
  touches it.
* Recipe-data isolation in the merge: cloning a panel into one side of
  the merge must NOT carry recipe rows through ``merge()`` (the merge
  function deliberately omits any concat rule for ``recipe_resolved``).
"""
