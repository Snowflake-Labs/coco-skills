def test_backward_compat_no_new_flags_yields_empty_panel(synthetic_conversion: Path) -> None:
    """When neither --original-source-dir nor --migration-state-json is
    provided, the renderer behaves exactly as before: workload_dir is
    scanned, no rebasing happens, recipe_resolved is empty."""
    conv = synthetic_conversion
    assessment = build_assessment(
        project="tier-b-syn",
        analysis_json=conv / "analysis.json",
        workload_dir=conv / "Output",
    )
    assert assessment.recipe_resolved == []
    # The finding's line should be the POST-recipe line (7), since rebasing
    # is disabled without the new flags.
    assert assessment.detailed_findings[0].lines == "7"


# ---------------------------------------------------------------------------
# New flag path: --migration-state-json drives everything
# ---------------------------------------------------------------------------


def test_migration_state_only_materializes_and_rebases(synthetic_conversion: Path) -> None:
    """Passing only --migration-state-json: renderer derives workload_dir,
    materializes the phase-0-source tag, rebases findings, and populates
    the recipe_resolved panel."""
    conv = synthetic_conversion
    assessment = build_assessment(
        project="tier-b-syn",
        analysis_json=conv / "analysis.json",
        migration_state_json=conv / "migration_state.json",
    )

    # Panel populated from recipe_edits.
    assert len(assessment.recipe_resolved) == 1
    row = assessment.recipe_resolved[0]
    assert isinstance(row, RecipeResolvedRow)
    assert row.file == "workload.py"
    assert row.line == 3
    assert row.recipe_id == "spark_builder_drop_master_init_session_rewrite"
    assert row.kind == "rewrite"

    # Finding line was rebased from POST line 7 → ORIGINAL line 5.
    assert assessment.detailed_findings[0].lines == "5"


def test_explicit_original_source_dir_overrides_materialize(
    synthetic_conversion: Path, tmp_path: Path
) -> None:
    """When --original-source-dir is explicit, the renderer does NOT
    materialize from git — it scans the provided dir directly."""
    conv = synthetic_conversion
    # Hand-build an alternative original source dir that differs slightly
    # (so we can prove the renderer used IT, not the git tag).
    alt = tmp_path / "alt-orig"
    alt.mkdir()
    (alt / "workload.py").write_text(
        # 4 lines — wildly different from both original and post versions.
        "X = 1\nY = 2\nZ = 3\nW = 4\n",
        encoding="utf-8",
    )

    assessment = build_assessment(
        project="tier-b-syn",
        analysis_json=conv / "analysis.json",
        workload_dir=conv / "Output",
        original_source_dir=alt,
        migration_state_json=conv / "migration_state.json",
    )
    # The panel still comes from migration_state_json[recipe_edits] (panel
    # is independent of the source-dir wiring).
    assert len(assessment.recipe_resolved) == 1
    # The scan reads from alt/, so file_types should reflect it.
    py_rows = [r for r in assessment.file_types if r.extension.lower() in {"python", ".py", "py"}]
    # At least one row referencing the single-file alt workspace.
    assert assessment.workload.files_scanned >= 1


# ---------------------------------------------------------------------------
# Recipe-data isolation in merge()
# ---------------------------------------------------------------------------


def test_merge_does_not_propagate_recipe_resolved() -> None:
    """The Assessment.merge() function must NOT concatenate recipe_resolved
    rows. Recipe data is assigned exclusively by build_assessment AFTER the
    merge. If a developer ever adds a concat rule here, recipe rows would
    leak in via the analyzer / scanner IR side."""
    a = Assessment()
    a.recipe_resolved = [
        RecipeResolvedRow(file="a.py", line=1, recipe_id="x_rewrite", kind="rewrite"),
    ]
    b = Assessment()
    b.recipe_resolved = [
        RecipeResolvedRow(file="b.py", line=2, recipe_id="y_rewrite", kind="rewrite"),
    ]

    merged = a.merge(b)
    # Whichever side wins, the merge MUST NOT have concatenated them.
    # Sanity: total length stays <= 1 (the result is at most one side's
    # rows, never both summed). The current implementation leaves the
    # merge target's list untouched, so we expect a's row to survive.
    assert len(merged.recipe_resolved) <= 1, (
        "Assessment.merge() must NOT concatenate recipe_resolved. "
        "Recipe data is assigned post-merge by render_assessment."
    )


def test_merge_signature_has_no_recipe_resolved_concat_in_source() -> None:
    """Source-level guarantee: Assessment.merge MUST NOT mention
    recipe_resolved in any way (no concat, no copy, no read). This catches
    a class of bugs that pure-behavioural assertions would miss."""
    import assess_ir
    merge_src = inspect.getsource(Assessment.merge)
    assert "recipe_resolved" not in merge_src, (
        "Assessment.merge must NOT touch recipe_resolved — the panel is "
        "post-merge assignment only (Tier-B Recipe-Data Isolation "
        "Guarantee). Source contains:\n" + merge_src
    )


